function finding(
  id: string,
  area: AuditFinding['area'],
  severity: AuditFinding['severity'],
  keep: boolean,
  title: string,
  observation: string,
  recommendation: string,
  affects: string[],
  v1Ref: string,
  ...images: string[]
): AuditFinding {
  return {
    id,
    area,
    severity,
    keep,
    title,
    observation,
    recommendation,
    affects,
    v1Ref,
    evidence: images.map((s) => '/audit/' + s + '.png'),
  }
}

